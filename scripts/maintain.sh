#!/usr/bin/env bash
# Trusted default-branch-only release-pins maintenance.
set -euo pipefail

: "${GITHUB_REPOSITORY:?}"
: "${GITHUB_SHA:?}"
: "${GH_TOKEN:?}"

readonly REPO="$GITHUB_REPOSITORY"
readonly BRANCH="automation/release-pins"
readonly FILE="config/releases.lock.json"
readonly CANDIDATE=".candidate-releases.lock.json"
readonly BOT_MARKER="COSW_DEMO_AUTOMATED_RELEASE_PINS_V1"

die() { echo "release maintenance: $*" >&2; exit 1; }

python3 -m scripts.update_releases --output "$CANDIDATE"
open_pr="$(gh pr list --repo "$REPO" --head "$BRANCH" --base master --state open --json number --jq '.[0].number // empty')"

write_lock_to_branch() {
  local file_sha encoded
  file_sha="$(gh api "repos/$REPO/contents/$FILE?ref=$BRANCH" --jq '.sha')"
  encoded="$(base64 -w0 < "$CANDIDATE")"
  gh api --silent --method PUT "repos/$REPO/contents/$FILE" \
    -f branch="$BRANCH" -f sha="$file_sha" -f content="$encoded" \
    -f message="chore(deps): refresh immutable release pins"
}

if [[ -z "$open_pr" ]]; then
  if cmp -s "$FILE" "$CANDIDATE"; then
    echo "Release pins already match eligible immutable releases."
    exit 0
  fi

  # Never force-reset an unexpected branch.
  if gh api --silent "repos/$REPO/git/ref/heads/$BRANCH" >/dev/null 2>&1; then
    die "$BRANCH exists without an open PR"
  fi
  gh api --silent --method POST "repos/$REPO/git/refs" \
    -f ref="refs/heads/$BRANCH" -f sha="$GITHUB_SHA"
  write_lock_to_branch

  gh pr create --repo "$REPO" --base master --head "$BRANCH" \
    --title "chore(deps): update immutable COSW and Remotish releases" \
    --body "$(cat <<EOF
$BOT_MARKER

Lock-only update from immutable Codellei release assets with published SHA-256
digests. Both browser extensions come from one Remotish release.

Explicit workflow_dispatch validates the branch head; successful CI is required
before optional unattended merge. Master requalifies before Pages publication.
EOF
)"

  # Ordinary PR events generated by GITHUB_TOKEN can require manual approval.
  # Explicit dispatch creates the actual automated qualification run.
  gh workflow run pages.yml --repo "$REPO" --ref "$BRANCH"
  echo "Created release-update PR and dispatched qualification."
  exit 0
fi

pr_json="$(gh api "repos/$REPO/pulls/$open_pr")"
jq -e --arg branch "$BRANCH" --arg repo "$REPO" \
  '.state=="open" and .draft==false and .base.ref=="master" and
   .head.ref==$branch and .head.repo.full_name==$repo and
   (.user.login=="github-actions[bot]" or .user.login=="app/github-actions")' \
  <<< "$pr_json" >/dev/null || die "bot PR identity, branch, or base changed"

body="$(jq -r '.body // ""' <<< "$pr_json")"
[[ "$body" == *"$BOT_MARKER"* ]] || die "bot marker missing"
changed="$(gh api --paginate "repos/$REPO/pulls/$open_pr/files?per_page=100" --jq '.[].filename')"
[[ "$changed" == "$FILE" ]] || die "automated PR modifies unexpected files"

gh api "repos/$REPO/contents/$FILE?ref=$BRANCH" \
  --jq '.content' | tr -d '\n' | base64 -d > ".pr-release-pins.json"

if ! cmp -s ".pr-release-pins.json" "$CANDIDATE"; then
  write_lock_to_branch
  gh workflow run pages.yml --repo "$REPO" --ref "$BRANCH"
  echo "Refreshed candidate to newer immutable releases; CI re-dispatched."
  exit 0
fi

head_sha="$(jq -r '.head.sha' <<< "$pr_json")"
runs="$(gh api "repos/$REPO/actions/workflows/pages.yml/runs?branch=automation%2Frelease-pins&event=workflow_dispatch&per_page=40")"
current="$(jq -c --arg sha "$head_sha" \
  '[.workflow_runs[] | select(.head_sha==$sha)] | sort_by(.created_at) | last // empty' \
  <<< "$runs")"

if [[ -z "$current" ]]; then
  gh workflow run pages.yml --repo "$REPO" --ref "$BRANCH"
  echo "Dispatched qualification on current head $head_sha."
  exit 0
fi

status="$(jq -r '.status' <<< "$current")"
conclusion="$(jq -r '.conclusion // ""' <<< "$current")"
case "$status" in
  queued|waiting|pending|in_progress|requested)
    echo "Qualification still $status on $head_sha."
    exit 0
    ;;
  completed)
    [[ "$conclusion" == "success" ]] ||
      die "qualification $conclusion on $head_sha; production unchanged"
    ;;
  *) die "unknown qualification status: $status" ;;
esac

if [[ "${AUTO_PROMOTE_ENABLED:-}" != "true" ]]; then
  echo "Qualified PR #$open_pr. Enable AUTO_PROMOTE_ENABLED=true after owner review."
  exit 0
fi

# Guard exact tested SHA; do not bypass branch protection or review requirements.
gh pr merge "$open_pr" --repo "$REPO" --squash --delete-branch \
  --match-head-commit "$head_sha"

# Bot merges do not trigger push workflows. Master requalifies before deployment.
gh workflow run pages.yml --repo "$REPO" --ref master
echo "Promoted qualified release pins; started master qualification/deployment."
